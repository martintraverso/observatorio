import { chromium, devices } from '@playwright/test';
const s = process.argv[2];
const b = await chromium.launch();
const errores = [];
const p = await (await b.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
p.on('pageerror', (e) => errores.push(e.message));
await p.goto('http://localhost:4199/observatorio/territorio/departamento/07');
await p.waitForTimeout(1500);
await p.screenshot({ path: `${s}/ficha-depto.png`, fullPage: true });
const m = await (await b.newContext({ ...devices['Pixel 7'], viewport: { width: 390, height: 844 } })).newPage();
m.on('pageerror', (e) => errores.push(e.message));
await m.goto('http://localhost:4199/observatorio/territorio/segmento/0701001');
await m.waitForTimeout(1500);
console.log('desborde movil', await m.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth), 'errores', JSON.stringify(errores));
await m.screenshot({ path: `${s}/ficha-segmento.png`, fullPage: true });
await b.close();
